    private static void tour(ClientGameTestContext context, TestSingleplayerContext world, TestServerContext server, DaedalusTheme theme)
    {
        var pos = closestDistrict(theme);
        var themeName = theme.getSerializedName();
        long seed = server.computeOnServer(minecraft -> VoidDaedalus.level(minecraft).getSeed());
        var plan = DistrictPlans.get(seed, pos);
        var bridge = DaedalusBridges.between(seed, pos, Compass.EAST).getFirst();

        double x = bridge.worldX(16, LANE_CENTRE) + 0.5;
        double z = bridge.worldZ(16, LANE_CENTRE) + 0.5;
        double y = bridge.walkY(16);
        shoot(context, world, server, "daedalus-" + themeName + "-bridge-to-district", x, y, z, WEST, 0);
        shoot(context, world, server, "daedalus-" + themeName + "-chasm", x, y + 1, z, SOUTH, 5);

        var landing = plan.landings().stream().filter(candidate -> candidate.direction() == Compass.EAST).findFirst().orElse(plan.landings().getFirst());
        shootCorridor(context, world, server, plan, landing, "daedalus-" + themeName + "-corridor");
        shootCorridorIntoRoom(context, world, server, plan, "daedalus-" + themeName + "-corridor-into-room");
        shootVistas(context, world, server, plan, "daedalus-" + themeName + "-vista");

        var seen = EnumSet.noneOf(RoomShape.class);
        var largestFirst = java.util.Arrays.stream(plan.rooms())
                .sorted(java.util.Comparator.comparingInt((Room room) -> room.cellsWide() * room.cellsDeep()).reversed())
                .toList();
        for (var room : largestFirst)
        {
            if (room.shape() != RoomShape.PLAIN && !seen.add(room.shape()))
                continue;
            if (room.shape() == RoomShape.PLAIN && !seen.add(RoomShape.PLAIN))
                continue;
            shootRoom(context, world, server, plan, room, "daedalus-" + themeName + "-room-" + room.shape().name().toLowerCase());
            if (room.shape() == RoomShape.ATRIUM)
                shootRingFlight(context, world, server, plan, room, "daedalus-" + themeName + "-ring-flight");
        }
    }

    /**
     * The flight from an atrium's second walkway up to its third, from the void beside it, so its rail on both floors shows.
     */
    private static void shootRingFlight(ClientGameTestContext context, TestSingleplayerContext world, TestServerContext server, DistrictPlan plan, Room room, String name)
    {
        if (room.maxK() - room.minK() < 2)
            return;
        int minX = plan.pos.originX() + room.minI() * DistrictPos.CELL + 1;
        int maxX = plan.pos.originX() + room.maxI() * DistrictPos.CELL + DistrictPos.CELL - 2;
        int minZ = plan.pos.originZ() + room.minJ() * DistrictPos.CELL + 1;
        int maxZ = plan.pos.originZ() + room.maxJ() * DistrictPos.CELL + DistrictPos.CELL - 2;
        int y = DistrictPos.floorY(room.minK() + 1) + 1;
        BlockPos flight = server.computeOnServer(minecraft ->
        {
            var level = VoidDaedalus.level(minecraft);
            for (int z = minZ; z <= maxZ; z++)
            {
                for (int x = minX; x <= maxX; x++)
                {
                    if (level.getBlockState(new BlockPos(x, y, z)).getBlock() instanceof net.minecraft.world.level.block.StairBlock)
                        return new BlockPos(x, y, z);
                }
            }
            return null;
        });
        expect(flight != null, "The atrium " + room + " has no flight up from its second walkway");
        double centreX = (minX + maxX + 1) / 2.0;
        double centreZ = (minZ + maxZ + 1) / 2.0;
        double dx = centreX - flight.getX();
        double dz = centreZ - flight.getZ();
        double length = Math.max(1, Math.sqrt(dx * dx + dz * dz));
        double cameraX = flight.getX() + 0.5 + dx / length * 6;
        double cameraZ = flight.getZ() + 0.5 + dz / length * 6;
        float yaw = (float) Math.toDegrees(Math.atan2(-(flight.getX() + 0.5 - cameraX), flight.getZ() + 0.5 - cameraZ));
        server.runCommand("effect give @a night_vision infinite 0 true");
        shoot(context, world, server, name, cameraX, y + 3, cameraZ, yaw, 25);
        shoot(context, world, server, name + "-top", cameraX, y + DistrictPos.CELL + 2, cameraZ, yaw, 40);
        server.runCommand("effect clear @a night_vision");
    }

    private static void shootCorridor(ClientGameTestContext context, TestSingleplayerContext world, TestServerContext server, DistrictPlan plan, DistrictPlan.Landing landing, String name)
    {
        double x = plan.pos.originX() + landing.i() * DistrictPos.CELL + LANE_CENTRE + 0.5;
        double z = plan.pos.originZ() + landing.j() * DistrictPos.CELL + LANE_CENTRE + 0.5;
        float yaw = switch (Compass.opposite(landing.direction()))
        {
            case Compass.NORTH -> NORTH;
            case Compass.EAST -> EAST;
            case Compass.SOUTH -> SOUTH;
            default -> WEST;
        };
        shoot(context, world, server, name, x, DistrictPos.floorY(landing.k()) + 1, z, yaw, 0);
    }

    /**
     * From the middle of a corridor cell, towards the largest of the small rooms that passages open into, the kind met most often.
     */
    private static void shootCorridorIntoRoom(ClientGameTestContext context, TestSingleplayerContext world, TestServerContext server, DistrictPlan plan, String name)
    {
        var small = java.util.Arrays.stream(plan.rooms())
                .filter(room -> room.minK() == room.maxK() && room.cellsWide() * room.cellsDeep() <= 4)
                .sorted(java.util.Comparator.comparingInt((Room room) -> room.cellsWide() * room.cellsDeep()).reversed())
                .toList();
        for (var room : small)
        {
            for (int side = 0; side < Compass.COUNT; side++)
            {
                for (int along = 0; along < Math.max(room.cellsWide(), room.cellsDeep()); along++)
                {
                    int edgeI = side == Compass.EAST ? room.maxI() : side == Compass.WEST ? room.minI() : Math.min(room.maxI(), room.minI() + along);
                    int edgeJ = side == Compass.SOUTH ? room.maxJ() : side == Compass.NORTH ? room.minJ() : Math.min(room.maxJ(), room.minJ() + along);
                    int i = edgeI + Compass.dx(side);
                    int j = edgeJ + Compass.dz(side);
                    if (!plan.isCorridorOpenTowards(i, room.minK(), j, Compass.opposite(side)))
                        continue;
                    shootCorridor(context, world, server, plan, new DistrictPlan.Landing(i, room.minK(), j, side), name + "-" + room.cellsWide() + "x" + room.cellsDeep());
                    shootThreshold(context, world, server, plan, edgeI, room.minK(), edgeJ, side, name + "-threshold");
                    return;
                }
            }
        }
        throw new AssertionError("No small room with a corridor in front of it in " + plan.theme);
    }

    private static int clockwise(int direction)
    {
        return (direction + 1) & 3;
    }

    private static float yawOf(int direction)
    {
        return switch (direction)
        {
            case Compass.NORTH -> NORTH;
            case Compass.EAST -> EAST;
            case Compass.SOUTH -> SOUTH;
            default -> WEST;
        };
    }

    /**
     * Down from a catwalk and from a balcony, up from the floor of a vault, and out of a window onto the chasm.
     */
    private static void shootVistas(ClientGameTestContext context, TestSingleplayerContext world, TestServerContext server, DistrictPlan plan, String name)
    {
        boolean catwalk = false;
        boolean balcony = false;
        boolean vault = false;
        for (var opening : plan.voids())
        {
            if (!vault && opening.shape() == RoomShape.VAULT)
            {
                double x = plan.pos.originX() + (opening.minI() + opening.maxI() + 1) * DistrictPos.CELL / 2.0;
                double z = plan.pos.originZ() + (opening.minJ() + opening.maxJ() + 1) * DistrictPos.CELL / 2.0;
                shoot(context, world, server, name + "-vault-up", x, DistrictPos.floorY(opening.minK()) + 1, z, EAST, -55);
                vault = true;
            }
            for (int k = opening.maxK(); k >= opening.minK() && !(catwalk && balcony); k--)
            {
                for (int j = opening.minJ(); j <= opening.maxJ(); j++)
                {
                    for (int i = opening.minI(); i <= opening.maxI(); i++)
                    {
                        double cellX = plan.pos.originX() + i * DistrictPos.CELL;
                        double cellZ = plan.pos.originZ() + j * DistrictPos.CELL;
                        double y = DistrictPos.floorY(k) + 1;
                        for (int side = 0; side < Compass.COUNT; side++)
                        {
                            if (!catwalk && plan.isCatwalk(i, k, j) && plan.isCatwalkOpen(i, k, j, side))
                            {
                                shoot(context, world, server, name + "-catwalk", cellX + LANE_CENTRE + 0.5, y, cellZ + LANE_CENTRE + 0.5, yawOf(clockwise(side)), 50);
                                catwalk = true;
                            }
                            if (!balcony && plan.hasBalcony(i, k, j, side))
                            {
                                double inset = side == Compass.NORTH || side == Compass.WEST ? 1.5 : DistrictPos.CELL - 1.5;
                                double x = cellX + (Compass.dx(side) != 0 ? inset : LANE_CENTRE + 0.5);
                                double z = cellZ + (Compass.dz(side) != 0 ? inset : LANE_CENTRE + 0.5);
                                shoot(context, world, server, name + "-balcony", x, y, z, yawOf(Compass.opposite(side)), 45);
                                balcony = true;
                            }
                        }
                    }
                }
            }
        }
        expect(catwalk && balcony, "No catwalk or no balcony to look from in " + plan.theme);
        shootChasmWindow(context, world, server, plan, name + "-chasm-window");
    }

    private static void shootChasmWindow(ClientGameTestContext context, TestSingleplayerContext world, TestServerContext server, DistrictPlan plan, String name)
    {
        for (int k = DistrictPos.TIERS - 1; k >= 0; k--)
        {
            for (int along = 1; along < DistrictPos.CELLS - 1; along++)
            {
                int[][] cells = { { DistrictPos.CELLS - 1, along, Compass.EAST }, { along, DistrictPos.CELLS - 1, Compass.SOUTH } };
                for (int[] cell : cells)
                {
                    if (!plan.hasWindow(cell[0], k, cell[1], cell[2]))
                        continue;
                    double x = plan.pos.originX() + cell[0] * DistrictPos.CELL + LANE_CENTRE + 0.5;
                    double z = plan.pos.originZ() + cell[1] * DistrictPos.CELL + LANE_CENTRE + 0.5;
                    shoot(context, world, server, name, x, DistrictPos.floorY(k) + 1, z, yawOf(cell[2]), 5);
                    return;
                }
            }
        }
    }

    /**
     * Just inside a room's door, looking in.
     */
    private static void shootThreshold(ClientGameTestContext context, TestSingleplayerContext world, TestServerContext server, DistrictPlan plan, int i, int k, int j, int doorSide, String name)
    {
        int inside = doorSide == Compass.NORTH || doorSide == Compass.WEST ? 1 : DistrictPos.CELL - 2;
        double x = plan.pos.originX() + i * DistrictPos.CELL + (Compass.dx(doorSide) != 0 ? inside : LANE_CENTRE) + 0.5;
        double z = plan.pos.originZ() + j * DistrictPos.CELL + (Compass.dz(doorSide) != 0 ? inside : LANE_CENTRE) + 0.5;
        float yaw = switch (Compass.opposite(doorSide))
        {
            case Compass.NORTH -> NORTH;
            case Compass.EAST -> EAST;
            case Compass.SOUTH -> SOUTH;
            default -> WEST;
        };
        shoot(context, world, server, name, x, DistrictPos.floorY(k) + 1, z, yaw, 0);
    }

    /**
     * A material found in a painted district, with the way out of the wall for a shrine.
     */
    private record Found(int x, int y, int z, int open)
    {
    }

    private interface Spot
    {
        boolean matches(DaedalusCanvas canvas, int x, int y, int z);
    }

    private static Found find(long seed, Spot spot, DaedalusTheme... themes)
    {
        for (var theme : themes)
        {
            var found = find(seed, theme, spot);
            if (found != null)
                return found;
        }
        throw new AssertionError("No relic found in " + RELIC_DISTRICTS + " districts each of " + java.util.Arrays.toString(themes));
    }

    private static Found find(long seed, DaedalusTheme theme, Spot spot)
    {
        var canvas = new DaedalusCanvas(DistrictPos.SIZE, DistrictPos.SIZE);
        int searched = 0;
        for (int radius = 0; radius < 64 && searched < RELIC_DISTRICTS; radius++)
        {
            for (int dz = -radius; dz <= radius; dz++)
            {
                for (int dx = -radius; dx <= radius; dx++)
                {
                    var pos = new DistrictPos(dx, dz);
                    if (Math.max(Math.abs(dx), Math.abs(dz)) != radius || DaedalusTheme.at(pos) != theme)
                        continue;
                    searched++;
                    canvas.reset(pos.originX(), pos.originZ());
                    DistrictPlans.paint(seed, canvas);
                    for (int y = 1; y < DistrictPos.TOP_Y; y++)
                    {
                        for (int z = canvas.minZ(); z <= canvas.maxZ(); z++)
                        {
                            for (int x = canvas.minX(); x <= canvas.maxX(); x++)
                            {
                                if (!spot.matches(canvas, x, y, z))
                                    continue;
                                int open = -1;
                                for (int side = 0; side < Compass.COUNT; side++)
                                {
                                    if (canvas.get(x + Compass.dx(side), y, z + Compass.dz(side)) == DaedalusMaterial.AIR)
                                        open = side;
                                }
                                return new Found(x, y, z, open);
                            }
                        }
                    }
                }
            }
        }
        return null;
    }

    private static int airAbove(DaedalusCanvas canvas, int x, int y, int z)
    {
        int air = 0;
        while (canvas.get(x, y + air + 1, z) == DaedalusMaterial.AIR)
            air++;
        return air;
    }

    /**
     * Altar circles in a room and under a vault, monoliths of the Writhing and a shrine in a niche, out of real chunks. The altars find all eight of their pillars, so a circle found here works.
     */
    private static void visitRelics(ClientGameTestContext context, TestSingleplayerContext world, TestServerContext server)
    {
        long seed = server.computeOnServer(minecraft -> VoidDaedalus.level(minecraft).getSeed());
        Spot roomAltar = (canvas, x, y, z) -> canvas.get(x, y, z) == DaedalusMaterial.ALTAR && airAbove(canvas, x, y, z) < VAULT_AIR;
        Spot vaultAltarSpot = (canvas, x, y, z) -> canvas.get(x, y, z) == DaedalusMaterial.ALTAR && airAbove(canvas, x, y, z) >= VAULT_AIR;
        Spot ring = (canvas, x, y, z) -> canvas.get(x, y, z) == DaedalusMaterial.SHRINE_LAMP && canvas.get(x + 3, y - 1, z).isMonolith() && canvas.get(x - 3, y - 1, z).isMonolith();
        Spot niche = (canvas, x, y, z) -> canvas.get(x, y, z) == DaedalusMaterial.SHRINE_LAMP;
        var altar = find(seed, roomAltar, DaedalusTheme.GALLERY, DaedalusTheme.ARCHIVE, DaedalusTheme.STAIRWELL, DaedalusTheme.CISTERN);
        var vaultAltar = find(seed, vaultAltarSpot, DaedalusTheme.STAIRWELL, DaedalusTheme.GALLERY, DaedalusTheme.ARCHIVE, DaedalusTheme.CISTERN, DaedalusTheme.WRITHING);
        var monoliths = find(seed, ring, DaedalusTheme.WRITHING, DaedalusTheme.WARREN);
        var shrine = find(seed, niche, DaedalusTheme.ARCHIVE, DaedalusTheme.GALLERY);

        for (var found : new Found[] { altar, vaultAltar })
        {
            server.runOnServer(minecraft ->
            {
                var level = VoidDaedalus.level(minecraft);
                var pos = new BlockPos(found.x(), found.y(), found.z());
                level.getChunk(pos);
                expect(level.getBlockEntity(pos) instanceof VoidAltarTile, "The altar at " + pos + " has no block entity: " + level.getBlockEntity(pos));
                var tile = (VoidAltarTile) level.getBlockEntity(pos);
                tile.searchPillars();
                expect(tile.foundPillars() == ALTAR_PILLARS, "The altar at " + pos + " finds " + tile.foundPillars() + " pillars");
                expect(level.getBlockEntity(pos.offset(1, 0, 3)) instanceof VoidPillarTile, "Pillars of the altar at " + pos + " have no block entity");
            });
        }

        shoot(context, world, server, "daedalus-relic-altar", altar.x() + 5.5, altar.y() + 2.5, altar.z() + 5.5, 135, 20);
        shoot(context, world, server, "daedalus-relic-altar-close", altar.x() + 0.5, altar.y() + 1.6, altar.z() + 3.5, NORTH, 25);
        shoot(context, world, server, "daedalus-relic-vault", vaultAltar.x() + 9.5, vaultAltar.y() + 3.5, vaultAltar.z() + 9.5, 135, 12);
        shoot(context, world, server, "daedalus-relic-vault-up", vaultAltar.x() + 0.5, vaultAltar.y() + 1.6, vaultAltar.z() + 5.5, NORTH, -30);
        shoot(context, world, server, "daedalus-relic-monoliths", monoliths.x() + 4.5, monoliths.y() + 1, monoliths.z() + 4.5, 135, 15);
        expect(shrine.open() >= 0, "The shrine at " + shrine + " opens onto nothing");
        double viewX = shrine.x() + 0.5 + Compass.dx(shrine.open()) * 2.5;
        double viewZ = shrine.z() + 0.5 + Compass.dz(shrine.open()) * 2.5;
        shoot(context, world, server, "daedalus-relic-shrine", viewX, shrine.y() - 1, viewZ, yawOf(Compass.opposite(shrine.open())), 15);
    }

    private static boolean isProp(DaedalusCanvas canvas, int x, int y, int z, DaedalusProp prop)
    {
        int raw = canvas.raw(x, y, z);
        return raw >= DaedalusCanvas.PROP_BASE && (raw - DaedalusCanvas.PROP_BASE) / Compass.COUNT == prop.ordinal();
    }

    /**
     * What breaks up the floors of large rooms: rows of tables, a statue on its dais, a pool round a font, and a bay cut into the wall.
     */
    private static void visitFeatures(ClientGameTestContext context, TestSingleplayerContext world, TestServerContext server)
    {
        long seed = server.computeOnServer(minecraft -> VoidDaedalus.level(minecraft).getSeed());
        Spot tableRow = (canvas, x, y, z) -> isProp(canvas, x, y, z, DaedalusProp.TABLE) && isProp(canvas, x + 1, y, z, DaedalusProp.TABLE) && isProp(canvas, x + 2, y, z, DaedalusProp.TABLE);
        Spot dais = (canvas, x, y, z) -> canvas.get(x, y, z) == DaedalusMaterial.FLOOR_TRIM && canvas.get(x + 2, y, z).isStep() && canvas.get(x - 2, y, z).isStep()
                                         && canvas.get(x, y, z + 2).isStep() && isProp(canvas, x, y + 1, z, DaedalusProp.PLINTH);
        Spot pool = (canvas, x, y, z) -> canvas.get(x, y, z) == DaedalusMaterial.COLUMN && canvas.get(x + 1, y, z) == DaedalusMaterial.WATER && isProp(canvas, x, y + 1, z, DaedalusProp.BASIN);
        Spot alcove = (canvas, x, y, z) -> canvas.get(x, y, z) == DaedalusMaterial.TRIM && canvas.get(x, y - 1, z) == DaedalusMaterial.AIR
                                           && !canvas.get(x, y - 4, z).isPassable()
                                           && (isArch(canvas, x - 1, y - 1, z) && isArch(canvas, x + 1, y - 1, z) || isArch(canvas, x, y - 1, z - 1) && isArch(canvas, x, y - 1, z + 1));

        var tables = find(seed, tableRow, DaedalusTheme.ARCHIVE, DaedalusTheme.GALLERY, DaedalusTheme.STAIRWELL);
        shoot(context, world, server, "daedalus-feature-tables", tables.x() - 2, tables.y() + 2.5, tables.z() + 3, -120, 25);
        var raised = find(seed, dais, DaedalusTheme.GALLERY, DaedalusTheme.ARCHIVE, DaedalusTheme.STAIRWELL);
        shoot(context, world, server, "daedalus-feature-dais", raised.x() + 4.5, raised.y() + 2, raised.z() + 4.5, 135, 20);
        var font = find(seed, pool, DaedalusTheme.CISTERN);
        shoot(context, world, server, "daedalus-feature-pool", font.x() + 5.5, font.y() + 2.5, font.z() + 5.5, 135, 25);
        Spot engine = (canvas, x, y, z) -> isProp(canvas, x, y, z, DaedalusProp.CONDENSER) && isProp(canvas, x + 2, y, z + 2, DaedalusProp.COIL);
        var machine = find(seed, engine, DaedalusTheme.CISTERN, DaedalusTheme.STAIRWELL, DaedalusTheme.ARCHIVE);
        shoot(context, world, server, "daedalus-feature-engine", machine.x() + 5.5, machine.y() + 2.5, machine.z() + 5.5, 135, 25);
        shoot(context, world, server, "daedalus-feature-engine-close", machine.x() + 0.5, machine.y() + 1.6, machine.z() + 4.5, NORTH, 15);
        Spot boilerBase = (canvas, x, y, z) -> canvas.get(x, y, z) == DaedalusMaterial.COPPER && canvas.get(x, y + 1, z) == DaedalusMaterial.COPPER && canvas.get(x + 1, y, z) == DaedalusMaterial.VENT;
        var boiler = find(seed, boilerBase, DaedalusTheme.CISTERN, DaedalusTheme.STAIRWELL);
        shoot(context, world, server, "daedalus-feature-boiler", boiler.x() + 5.5, boiler.y() + 1.6, boiler.z() + 2.5, 70, 10);
        shoot(context, world, server, "daedalus-feature-boiler-room", boiler.x() + 6.5, boiler.y() + 3.5, boiler.z() + 6.5, 135, 25);

        Spot crypt = (canvas, x, y, z) -> isProp(canvas, x, y, z, DaedalusProp.SARCOPHAGUS) && isProp(canvas, x + 2, y, z, DaedalusProp.SARCOPHAGUS)
                                          && (canvas.raw(x, y, z) - DaedalusCanvas.PROP_BASE) % Compass.COUNT == Compass.SOUTH;
        var sleeper = find(seed, crypt, DaedalusTheme.GALLERY, DaedalusTheme.ARCHIVE, DaedalusTheme.STAIRWELL);
        shoot(context, world, server, "daedalus-feature-crypt", sleeper.x() + 1.5, sleeper.y() + 1.8, sleeper.z() + 4.5, NORTH, 25);
        shoot(context, world, server, "daedalus-feature-crypt-row", sleeper.x() - 2.5, sleeper.y() + 2.5, sleeper.z() + 3.5, -120, 30);

        Spot pipeRun = (canvas, x, y, z) -> canvas.get(x, y, z) == DaedalusMaterial.PIPE_X && canvas.get(x + 1, y, z) == DaedalusMaterial.PIPE_X && canvas.get(x + 2, y, z) == DaedalusMaterial.PIPE_X
                                            && canvas.get(x, y - 1, z) == DaedalusMaterial.AIR && !canvas.get(x, y, z - 1).isPassable() && canvas.get(x, y - 1, z + 1) == DaedalusMaterial.AIR;
        var pipe = find(seed, pipeRun, DaedalusTheme.CISTERN, DaedalusTheme.STAIRWELL, DaedalusTheme.WARREN);
        shoot(context, world, server, "daedalus-feature-corridor-pipe", pipe.x() + 0.5, pipe.y() - 1.6, pipe.z() + 1.5, -80, -15);

        var bay = find(seed, alcove, DaedalusTheme.GALLERY, DaedalusTheme.STAIRWELL, DaedalusTheme.ARCHIVE);
        int feet = bay.y() - ALCOVE_KEYSTONE;
        int out = server.computeOnServer(minecraft ->
        {
            var level = VoidDaedalus.level(minecraft);
            for (int side = 0; side < Compass.COUNT; side++)
            {
                var pos = new BlockPos(bay.x() + Compass.dx(side) * 2, feet + 1, bay.z() + Compass.dz(side) * 2);
                if (!level.getBlockState(pos).isCollisionShapeFullBlock(level, pos))
                    return side;
            }
            return -1;
        });
        expect(out >= 0, "The alcove at " + bay + " opens onto nothing");
        shoot(context, world, server, "daedalus-feature-alcove", bay.x() + 0.5 + Compass.dx(out) * 4, feet, bay.z() + 0.5 + Compass.dz(out) * 4, yawOf(Compass.opposite(out)), 10);
    }

    private static boolean isArch(DaedalusCanvas canvas, int x, int y, int z)
    {
        int ordinal = canvas.get(x, y, z).ordinal();
        return ordinal >= DaedalusMaterial.ARCH_NORTH.ordinal() && ordinal <= DaedalusMaterial.ARCH_WEST.ordinal();
    }

    private static void shootRoom(ClientGameTestContext context, TestSingleplayerContext world, TestServerContext server, DistrictPlan plan, Room room, String name)
    {
        double x = plan.pos.originX() + room.minI() * DistrictPos.CELL + 2.5;
        double z = plan.pos.originZ() + (room.minJ() + room.maxJ() + 1) * DistrictPos.CELL / 2.0 + 0.5;
        int tier = room.shape() == RoomShape.FLOOD ? room.maxK() : room.minK();
        double y = DistrictPos.floorY(tier) + 1;
        shoot(context, world, server, name, x, y, z, EAST, 0);

        if (room.maxK() > room.minK() && room.shape() != RoomShape.FLOOD)
            shoot(context, world, server, name + "-above", x, DistrictPos.floorY(room.maxK()) + 3, z, EAST, 25);
        else if (room.shape() == RoomShape.PLAIN || room.shape() == RoomShape.VAULT)
            shoot(context, world, server, name + "-raised", x, y + 3, z, EAST, 35);
    }
