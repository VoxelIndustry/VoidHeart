    private static void checkEntry(ClientGameTestContext context, TestServerContext server)
    {
        server.runCommand("execute as @a run voidheart daedalus enter");
        context.waitTicks(20);
        int[] first = server.computeOnServer(DaedalusClientTest::checkStandingOnABridge);

        server.runCommand("execute as @a run voidheart daedalus enter");
        context.waitTicks(20);
        int[] second = server.computeOnServer(DaedalusClientTest::checkStandingOnABridge);
        expect(first[0] != second[0] || first[2] != second[2], "Each entry should lead somewhere new");
    }

    private static int[] checkStandingOnABridge(MinecraftServer minecraft)
    {
        var player = minecraft.getPlayerList().getPlayers().getFirst();
        expect(player.level().dimension() == VoidDaedalus.WORLD_KEY, "The player should be in the Daedalus, not in " + player.level().dimension());
        expect(!DistrictPos.isInsideDistrict(player.getBlockX(), player.getBlockZ()), "A player should arrive over a chasm, not at " + player.blockPosition());

        var level = (ServerLevel) player.level();
        var below = level.getBlockState(player.blockPosition().below());
        var feet = level.getBlockState(player.blockPosition());
        expect(!below.isAir() || !feet.isAir(), "There should be a deck under the arrival at " + player.blockPosition());
        expect(level.getBlockState(player.blockPosition().above()).isAir(), "There should be headroom at the arrival " + player.blockPosition());
        return new int[] { player.getBlockX(), player.getBlockY(), player.getBlockZ() };
    }

    private static void checkBounds(TestServerContext server)
    {
        server.runOnServer(minecraft ->
        {
            var level = VoidDaedalus.level(minecraft);
            expect(level.getMinY() == 0 && level.getHeight() == DistrictPos.HEIGHT, "The Daedalus should be " + DistrictPos.HEIGHT + " high, it is " + level.getHeight());

            var floor = new BlockPos(5, 0, 5);
            var ceiling = new BlockPos(5, DistrictPos.TOP_Y, 5);
            var chasmFloor = new BlockPos(DistrictPos.SIZE + 5, 0, 5);
            for (var pos : new BlockPos[] { floor, ceiling, chasmFloor })
            {
                var state = level.getBlockState(pos);
                expect(state.is(VoidHeartBlocks.POCKET_WALL), "The bounds should be pocket wall at " + pos + ", found " + state);
                expect(state.getDestroySpeed(level, pos) < 0, "The bounds should be indestructible at " + pos);
            }
            expect(VoidHeartBlocks.VOIDSTONE.defaultBlockState().getDestroySpeed(level, floor) > 0, "Walls should stay breakable");
        });
    }

