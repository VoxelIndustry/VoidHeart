    /**
     * Every block of a real chunk against its plan, for every theme. This also catches anything that changed after writing, like water flowing or stairs and walls reshaping.
     */
    private static void checkChunksMatchThePlan(MinecraftServer minecraft)
    {
        var level = VoidDaedalus.level(minecraft);
        var canvas = new DaedalusCanvas(16, 16);
        int[] rails = new int[3];
        for (var theme : DaedalusTheme.values())
        {
            var pos = closestDistrict(theme);
            for (int cz = 0; cz < CHECKED_CHUNKS_RADIUS; cz++)
            {
                for (int cx = 0; cx < CHECKED_CHUNKS_RADIUS; cx++)
                {
                    int minX = pos.originX() + cx * 2 * 16;
                    int minZ = pos.originZ() + cz * 2 * 16;
                    var chunk = level.getChunk(minX >> 4, minZ >> 4);
                    canvas.reset(minX, minZ);
                    DistrictPlans.paint(level.getSeed(), canvas);
                    var palette = DistrictPos.isInsideDistrict(minX, minZ) ? DaedalusPalette.of(DaedalusTheme.at(DistrictPos.at(minX, minZ))) : DaedalusPalette.chasm();
                    compare(level, chunk, canvas, palette, minX, minZ, nests(level.getSeed(), canvas, minX, minZ), rails);
                }
            }
        }
        expect(rails[0] > 0 && rails[1] > 0 && rails[2] > 0, "Too few rails were checked: " + rails[0] + " in all, " + rails[1] + " posts, " + rails[2] + " on a chunk edge");
    }

    /**
     * Barnacle nests grow over the painted district where its mobs are planned, found in their cells as the chunk writer finds them.
     */
    private static java.util.Set<BlockPos> nests(long seed, DaedalusCanvas canvas, int minX, int minZ)
    {
        var nests = new java.util.HashSet<BlockPos>();
        if (!DistrictPos.isInsideDistrict(minX, minZ))
            return nests;
        var plan = DistrictPlans.get(seed, DistrictPos.at(minX, minZ));
        var taken = new java.util.HashMap<String, java.util.Set<Long>>();
        for (var placement : plan.mobs().inChunk(minX >> 4, minZ >> 4))
        {
            if (placement.mob() != DaedalusMob.BARNACLE_NEST)
                continue;
            var spot = DaedalusMobSpots.find(canvas, plan.pos, placement, taken.computeIfAbsent(placement.i() + " " + placement.k() + " " + placement.j(), key -> new java.util.HashSet<>()));
            if (spot != null)
                nests.add(new BlockPos(spot.x(), spot.y(), spot.z()));
        }
        return nests;
    }

    /**
     * Rails are joined to their neighbours as they are written, so they must already be what a block update would reshape them into, as if broken and placed again.
     *
     * @param rails counts of the rails checked, of those standing as posts and of those on a chunk's edge
     */
    private static void compare(ServerLevel level, net.minecraft.world.level.chunk.ChunkAccess chunk, DaedalusCanvas canvas, DaedalusPalette palette, int minX, int minZ, java.util.Set<BlockPos> nests, int[] rails)
    {
        var at = new BlockPos.MutableBlockPos();
        for (int y = 0; y < DistrictPos.HEIGHT; y++)
        {
            for (int z = minZ; z < minZ + 16; z++)
            {
                for (int x = minX; x < minX + 16; x++)
                {
                    var wanted = palette.state(canvas.raw(x, y, z), y > 0 ? canvas.raw(x, y - 1, z) : 0, x, y, z);
                    var found = chunk.getBlockState(at.set(x, y, z));
                    if (DaedalusPalette.isRail(canvas.raw(x, y, z)))
                    {
                        var reshaped = Block.updateFromNeighbourShapes(found, level, at);
                        expect(found.getBlock() instanceof WallBlock && reshaped == found, "At " + at + " the rail " + found + " should already be joined as " + reshaped);
                        rails[0]++;
                        if (found.getValue(WallBlock.UP))
                            rails[1]++;
                        if (x == minX || x == minX + 15 || z == minZ || z == minZ + 15)
                            rails[2]++;
                        continue;
                    }
                    if (nests.contains(at))
                    {
                        expect(found.is(VoidHeartBlocks.BARNACLE_NEST), "At " + at + " a nest should have grown, the chunk has " + found);
                        continue;
                    }
                    expect(wanted == found, "At " + at + " the plan has " + wanted + " but the chunk has " + found);
                }
            }
        }
    }

    private static void checkBiomes(MinecraftServer minecraft)
    {
        var level = VoidDaedalus.level(minecraft);
        for (var theme : DaedalusTheme.values())
        {
            var pos = closestDistrict(theme);
            var inside = new BlockPos(pos.originX() + 40, 20, pos.originZ() + 40);
            var chasm = new BlockPos(pos.originX() + DistrictPos.SIZE + 16, 20, pos.originZ() + 40);
            level.getChunk(inside);
            level.getChunk(chasm);
            expect(isBiome(level.getBiome(inside), "daedalus_" + theme.getSerializedName()), "Wrong biome inside " + theme + ": " + level.getBiome(inside));
            expect(isBiome(level.getBiome(chasm), "daedalus_chasm"), "Wrong biome in a chasm: " + level.getBiome(chasm));
        }
    }

    private static boolean isBiome(net.minecraft.core.Holder<Biome> biome, String name)
    {
        return biome.unwrapKey().map(key -> key.identifier().getPath().equals(name)).orElse(false);
    }

    private static void timeGeneration(MinecraftServer minecraft)
    {
        long daedalus = timeChunks(VoidDaedalus.level(minecraft), TIMED_DISTRICTS_AWAY * DistrictPos.PITCH);
        long flat = timeChunks(minecraft.overworld(), 100_000);
        int count = (TIMED_CHUNKS_RADIUS * 2) * (TIMED_CHUNKS_RADIUS * 2);
        System.out.printf("Daedalus performance: %d new chunks in %d ms (%.2f ms each), the flat test overworld takes %d ms (%.2f ms each)%n",
                count, daedalus, daedalus / (float) count, flat, flat / (float) count);
    }

    private static long timeChunks(ServerLevel level, int blocksAway)
    {
        var centre = new ChunkPos(blocksAway >> 4, blocksAway >> 4);
        long start = System.nanoTime();
        for (int z = -TIMED_CHUNKS_RADIUS; z < TIMED_CHUNKS_RADIUS; z++)
        {
            for (int x = -TIMED_CHUNKS_RADIUS; x < TIMED_CHUNKS_RADIUS; x++)
                level.getChunk(centre.x() + x, centre.z() + z, ChunkStatus.FULL, true);
        }
        return (System.nanoTime() - start) / 1_000_000;
    }

    /**
     * Walks with the real movement key from the middle of a bridge into the district at its end, where the name should be announced.
     */
    private static void walkOffABridge(ClientGameTestContext context, TestSingleplayerContext world, TestServerContext server)
    {
        var from = closestDistrict(DaedalusTheme.GALLERY);
        long seed = server.computeOnServer(minecraft -> VoidDaedalus.level(minecraft).getSeed());
        var bridge = DaedalusBridges.between(seed, from, Compass.EAST).getFirst();
        server.runCommand("gamemode survival @a");
        server.runOnServer(minecraft ->
        {
            var player = minecraft.getPlayerList().getPlayers().getFirst();
            VoidDaedalus.arriveOn(player, bridge);
            player.getAbilities().invulnerable = true;
        });
        context.waitTicks(CHUNK_ARRIVAL_TICKS);
        world.getConnection().waitForChunksRender(false, CHUNK_TIMEOUT_TICKS);
        context.takeScreenshot("daedalus-walk-start");

        context.getInput().holdKey(options -> options.keyUp);
        boolean arrived = false;
        for (int waited = 0; waited < MAX_WALK_TICKS && !arrived; waited += WALK_STEP_TICKS)
        {
            context.waitTicks(WALK_STEP_TICKS);
            arrived = server.computeOnServer(minecraft ->
            {
                var player = minecraft.getPlayerList().getPlayers().getFirst();
                return DistrictPos.isInsideDistrict(player.getBlockX(), player.getBlockZ());
            });
        }
        context.waitTicks(TITLE_SHOWN_TICKS);
        context.getInput().releaseKey(options -> options.keyUp);
        expect(arrived, "Walking along a bridge should lead into a district");

        int expectedFloor = DistrictPos.floorY(bridge.toTier()) + 1;
        int y = server.computeOnServer(minecraft -> minecraft.getPlayerList().getPlayers().getFirst().getBlockY());
        expect(y == expectedFloor, "The player should have walked in at height " + expectedFloor + ", not " + y);

        context.takeScreenshot("daedalus-walk-title");
        server.runOnServer(minecraft -> minecraft.getPlayerList().getPlayers().getFirst().getAbilities().invulnerable = false);
        server.runCommand("gamemode spectator @a");
        context.waitTicks(5);
    }

