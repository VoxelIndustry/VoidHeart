/**
 * The Underway generated by real chunks under the Daedalus: that the world holds what was planned around each kind of fort's entry, and how its levels look from inside, lit for the camera and in their own dark.
 */
public class UnderwayClientTest implements FabricClientGameTest
{
    private static final int CHUNK_TIMEOUT_TICKS = 1200;
    private static final int CHECKED_RADIUS = 20;
    private static final int MIN_PROPS_CHECKED = 10;

    @Override
    public void runTest(ClientGameTestContext context)
    {
        try (var world = context.worldBuilder().create())
        {
            var server = world.getServer();
            world.getConnection().waitForChunksRender();
            server.runCommand("gamemode spectator @a");
            context.runOnClient(minecraft -> minecraft.options.setCameraType(CameraType.FIRST_PERSON));
            boolean hudWasHidden = context.computeOnClient(minecraft -> minecraft.gui.hud.isHidden());
            if (!hudWasHidden)
                context.getInput().pressKey(InputConstants.KEY_F1);

            var station = enter(context, world, UnderwayNode.STATION);
            checkWorldMatchesPlan(server, station, station.footAlong(), station.footAcross(), UnderwayLevels.ENTRY_FLOOR, UnderwayLevels.ENTRY_FLOOR + UnderwayLevels.ENTRY_HEIGHT + 1, MIN_PROPS_CHECKED);
            server.runCommand("effect give @a minecraft:night_vision infinite 0 true");
            look(context, world, station, "station-entry", first(station, UnderwayRoomKind.HATCH_LOBBY));
            look(context, world, station, "station-guard-room", first(station, UnderwayRoomKind.GUARD_ROOM));
            look(context, world, station, "station-gallery", first(station, UnderwayRoomKind.GALLERY));
            look(context, world, station, "station-barracks", first(station, UnderwayRoomKind.BARRACKS));
            look(context, world, station, "station-mess", first(station, UnderwayRoomKind.MESS));
            look(context, world, station, "station-stores", first(station, UnderwayRoomKind.STORES));
            var platform = first(station, UnderwayRoomKind.PLATFORM);
            look(context, world, station, "station-platform", platform);
            checkWorldMatchesPlan(server, station, platform.centreAlong(), 63, UnderwayLevels.BALLAST, UnderwayLevels.PLATFORM_FLOOR + 3, 0);
            shot(context, world, station, "station-trunk", platform.a0() + 4, 64, UnderwayLevels.BALLAST, platform.a0() + 40, 63, UnderwayLevels.BALLAST);
            var core = station.shafts().getFirst();
            shot(context, world, station, "station-core-stairs", core.landingAlong(), core.landingAcross(), UnderwayLevels.PLATFORM_FLOOR, core.a0() + 6, core.c0() + 6, UnderwayLevels.PLATFORM_FLOOR + 6);
            look(context, world, station, "station-magazine", first(station, UnderwayRoomKind.MAGAZINE));
            look(context, world, station, "station-depot", first(station, UnderwayRoomKind.DEPOT));
            server.runCommand("effect clear @a");
            look(context, world, station, "station-gallery-dark", first(station, UnderwayRoomKind.GALLERY));
            look(context, world, station, "station-platform-dark", first(station, UnderwayRoomKind.PLATFORM));

            var hub = enter(context, world, UnderwayNode.HUB);
            checkWorldMatchesPlan(server, hub, hub.footAlong(), hub.footAcross(), UnderwayLevels.ENTRY_FLOOR, UnderwayLevels.ENTRY_FLOOR + UnderwayLevels.ENTRY_HEIGHT + 1, MIN_PROPS_CHECKED);
            server.runCommand("effect give @a minecraft:night_vision infinite 0 true");
            var quadrant = first(hub, UnderwayRoomKind.PLATFORM);
            shot(context, world, hub, "hub-atrium-from-platform", quadrant.a0() + 1, quadrant.c0() + 1, quadrant.floorY(), 64, 64, UnderwayLevels.LIVING_FLOOR);
            shot(context, world, hub, "hub-atrium-from-balcony", 41, 41, UnderwayLevels.LIVING_FLOOR, 80, 80, UnderwayLevels.PLATFORM_FLOOR);
            look(context, world, hub, "hub-control-room", first(hub, UnderwayRoomKind.CONTROL_ROOM));

            var post = enter(context, world, UnderwayNode.POST);
            checkWorldMatchesPlan(server, post, post.footAlong(), post.footAcross(), UnderwayLevels.ENTRY_FLOOR, UnderwayLevels.ENTRY_FLOOR + UnderwayLevels.ENTRY_HEIGHT + 1, MIN_PROPS_CHECKED);
            look(context, world, post, "post-gallery", first(post, UnderwayRoomKind.GALLERY));
            server.runCommand("effect clear @a");
            if (!hudWasHidden)
                context.getInput().pressKey(InputConstants.KEY_F1);
        }
    }

    private static UnderwayFort enter(ClientGameTestContext context, TestSingleplayerContext world, UnderwayNode kind)
    {
        var server = world.getServer();
        server.runCommand("execute as @a run voidheart underway enter " + kind.name().toLowerCase());
        context.waitTicks(20);
        world.getConnection().waitForChunksRender(false, CHUNK_TIMEOUT_TICKS);
        return server.computeOnServer(minecraft ->
        {
            var player = player(minecraft);
            expect(player.level().dimension() == VoidDaedalus.WORLD_KEY, "The command did not lead into the Daedalus' dimension");
            var fort = UnderwayPlans.fort(VoidDaedalus.level(minecraft).getSeed(), DistrictPos.at(player.getBlockX(), player.getBlockZ()));
            expect(fort.node() == kind, "Asked for a " + kind + ", arrived over a " + fort.node());
            expect(player.getBlockY() == UnderwayLevels.ENTRY_FLOOR + 1, "The player stands at " + player.getBlockY() + ", not on the entry level");
            return fort;
        });
    }

    /** Compares the blocks around a place of a fort, between two heights, with the plan drawn for the same place. */
    private static void checkWorldMatchesPlan(TestServerContext server, UnderwayFort fort, int along, int across, int fromY, int toY, int minProps)
    {
        server.runOnServer(minecraft ->
        {
            var level = VoidDaedalus.level(minecraft);
            var canvas = new UnderwayCanvas(DistrictPos.PITCH, DistrictPos.PITCH);
            canvas.reset(fort.pos().originX(), fort.pos().originZ());
            UnderwayPlans.paint(level.getSeed(), canvas);

            int footX = fort.frame().x(along, across);
            int footZ = fort.frame().z(along, across);
            var rails = EnumSet.noneOf(UnderwayMaterial.class);
            int props = 0;
            for (int y = fromY; y <= toY; y++)
            {
                for (int z = footZ - CHECKED_RADIUS; z <= footZ + CHECKED_RADIUS; z++)
                {
                    for (int x = footX - CHECKED_RADIUS; x <= footX + CHECKED_RADIUS; x++)
                    {
                        if (x < canvas.minX() || x > canvas.maxX() || z < canvas.minZ() || z > canvas.maxZ())
                            continue;
                        var pos = new BlockPos(x, y, z);
                        var state = level.getBlockState(pos);
                        var material = canvas.get(x, y, z);
                        var prop = canvas.propAt(x, y, z);
                        if (prop != null)
                        {
                            expect(state.is(VoidHeartBlocks.underwayProp(prop)), "Planned " + prop + " at " + pos + ", found " + state);
                            expect(state.getValue(UnderwayPropBlock.FACING).get2DDataValue() == (canvas.propFacing(x, y, z) + 2) % 4, prop + " at " + pos + " faces " + state.getValue(UnderwayPropBlock.FACING));
                            props++;
                        }
                        else if (material == UnderwayMaterial.AIR)
                            expect(state.isAir() || state.is(VoidHeartBlocks.UNDERWAY_TRACK_TIE), "Planned air at " + pos + ", found " + state);
                        else if (material == UnderwayMaterial.SHELL || material == UnderwayMaterial.FLOOR)
                        {
                            boolean concrete = state.is(VoidHeartBlocks.UNDERWAY_CONCRETE) || state.is(VoidHeartBlocks.UNDERWAY_FORMED_CONCRETE)
                                    || state.is(VoidHeartBlocks.UNDERWAY_STAINED_CONCRETE) || state.is(VoidHeartBlocks.UNDERWAY_CRACKED_CONCRETE);
                            expect(concrete, "Planned concrete at " + pos + ", found " + state);
                            expect(state.getDestroySpeed(level, pos) < 0, "The shell at " + pos + " can be broken");
                        }
                        else if (material == UnderwayMaterial.ROCK)
                            expect(state.is(VoidHeartBlocks.POCKET_WALL), "Planned rock at " + pos + ", found " + state);
                        else if (material == UnderwayMaterial.PLATFORM)
                            expect(state.is(VoidHeartBlocks.UNDERWAY_STAINED_CONCRETE), "Planned a platform at " + pos + ", found " + state);
                        else if (material == UnderwayMaterial.BALLAST)
                            expect(state.is(VoidHeartBlocks.UNDERWAY_BALLAST), "Planned ballast at " + pos + ", found " + state);
                        else if (material == UnderwayMaterial.COLUMN || material == UnderwayMaterial.STEEL)
                            expect(state.is(VoidHeartBlocks.UNDERWAY_ARMOUR), "Planned armour at " + pos + ", found " + state);
                        else if (material.isRail())
                        {
                            boolean trunk = material == UnderwayMaterial.TRUNK_RAIL_X || material == UnderwayMaterial.TRUNK_RAIL_Z;
                            boolean alongX = material == UnderwayMaterial.TRUNK_RAIL_X || material == UnderwayMaterial.FEEDER_RAIL_X;
                            expect(state.is(trunk ? VoidHeartBlocks.UNDERWAY_TRUNK_RAIL : VoidHeartBlocks.UNDERWAY_FEEDER_RAIL), "Planned " + material + " at " + pos + ", found " + state);
                            expect((state.getValue(UnderwayTrackBlock.AXIS) == Direction.Axis.X) == alongX, material + " at " + pos + " lies along " + state.getValue(UnderwayTrackBlock.AXIS));
                            rails.add(material);
                        }
                        else if (material == UnderwayMaterial.STAIRS_NORTH || material == UnderwayMaterial.STAIRS_EAST || material == UnderwayMaterial.STAIRS_SOUTH || material == UnderwayMaterial.STAIRS_WEST)
                            expect(state.is(VoidHeartBlocks.UNDERWAY_STEEL_STAIRS), "Planned stairs at " + pos + ", found " + state);
                        else if (material == UnderwayMaterial.DOOR)
                            expect(state.is(VoidHeartBlocks.UNDERWAY_DOOR), "Planned a door at " + pos + ", found " + state);
                        else if (material == UnderwayMaterial.GRATING)
                            expect(state.is(VoidHeartBlocks.UNDERWAY_GRATING), "Planned grating at " + pos + ", found " + state);
                    }
                }
            }
            expect(props >= minProps, "Only " + props + " props stand around " + along + " " + across + " of the " + fort.node());
            if (fromY == UnderwayLevels.BALLAST)
                expect(!rails.isEmpty(), "No track was found along the platform of the " + fort.node());
            expect(level.getBlockState(new BlockPos(footX, 0, footZ)).is(VoidHeartBlocks.POCKET_WALL), "The districts' floor above the Underway is gone");
        });
    }

    private static UnderwayRoom first(UnderwayFort fort, UnderwayRoomKind kind)
    {
        return fort.rooms().stream().filter(room -> room.kind() == kind).findFirst().orElseThrow(() -> new AssertionError("The " + fort.node() + " has no " + kind));
    }

    /** Looks down a room's longer side from just inside one end. */
    private static void look(ClientGameTestContext context, TestSingleplayerContext world, UnderwayFort fort, String name, UnderwayRoom room)
    {
        boolean longAlong = room.a1() - room.a0() >= room.c1() - room.c0();
        int length = Math.min(24, longAlong ? room.a1() - room.a0() : room.c1() - room.c0());
        int along = longAlong ? room.a0() + 1 : room.centreAlong();
        int across = longAlong ? room.centreAcross() + (room.kind() == UnderwayRoomKind.PLATFORM ? 1 : 0) : room.c0() + 1;
        shot(context, world, fort, name, along, across, room.floorY(), longAlong ? along + length : along, longAlong ? across : across + length, room.floorY());
    }

    private static void shot(ClientGameTestContext context, TestSingleplayerContext world, UnderwayFort fort, String name, int along, int across, int floorY, int toAlong, int toAcross, int toFloorY)
    {
        var frame = fort.frame();
        world.getServer().runCommand("execute in voidheart:daedalus run tp @a "
                + aimedPose(frame.x(along, across) + 0.5, floorY + 1.2, frame.z(along, across) + 0.5, frame.x(toAlong, toAcross) + 0.5, toFloorY + 2, frame.z(toAlong, toAcross) + 0.5));
        context.waitTicks(10);
        world.getConnection().waitForChunksRender(false, CHUNK_TIMEOUT_TICKS);
        context.takeScreenshot(TestScreenshotOptions.of("underway-" + name).withSize(1280, 720));
    }
}
