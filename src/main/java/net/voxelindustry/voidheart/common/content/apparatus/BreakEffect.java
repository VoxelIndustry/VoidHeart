package net.voxelindustry.voidheart.common.content.apparatus;

/**
 * What a break core does the moment the shield gives out.
 */
public enum BreakEffect
{
    /** Throws back and hurts the monsters standing close. */
    PULSE,
    /** Steps the wearer away from the blow and hides them for a moment. */
    BLINK,
    /** Slows everything hostile around the wearer. */
    STASIS,
    /** Heals the wearer a little. */
    MEND
}
